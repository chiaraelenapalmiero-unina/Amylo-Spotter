#!/usr/bin/env python3
"""
Distribution of buried vs. exposed residues, read from a DSSP CSV file.

Extracts the ACC_norm values from CSV files generated by
batch_dssp_parse, for all secondary structure types, plots their density
(KDE, bin-free) and computes the local minima of that density.
Supports any column whose name contains 'acc_norm' (case-insensitive),
including 'ACC_norm %'.

Usage:
    python plot_acc_norm_kde.py dssp_summary.csv [--points N]
"""
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import argparse
from scipy.stats import gaussian_kde
from scipy.signal import find_peaks


def main(csv_path, n_points=1000):
    """
    Loads the CSV, builds a KDE of the accessibility values, finds its
    local minima, and displays the resulting density plot.

    Args:
        csv_path: Path to the input CSV file. Must contain at least one
            column whose name includes "acc_norm" (case-insensitive),
            e.g. "ACC_norm" or "ACC_norm %".
        n_points: Number of points used to sample the KDE curve along the
            x-axis (default: 1000). Higher values give a smoother curve
            but take slightly longer to compute.
    """
    df = pd.read_csv(csv_path)

    columns = [c for c in df.columns if 'acc_norm' in c.lower()]
    acc_col = columns[0]

    # Take all values without filtering by the 'SS' (secondary structure) column
    values = df[acc_col].values
    
    print(f"Processed {len(values)} total residues.")

    # Compute normalized ACC% if needed
    if 'percent' not in acc_col.lower():
        df['ACC_percent'] = df[acc_col]
    else:
        df['ACC_percent'] = df[acc_col]

    # Extract the ACC_percent values
    values = df['ACC_percent'].values

    # Build a continuous KDE (kernel density estimate)
    kde = gaussian_kde(values)
    xs = np.linspace(0, values.max(), n_points)
    ys = kde(xs)

    # Find local minima (invert ys to reuse a peak-finding function)
    minima_idx, _ = find_peaks(-ys)
    minima = xs[minima_idx]
    print(f"Local density minima: {np.round(minima, 2)}")

    # Plot the density (KDE), bin-free
    plt.figure(figsize=(8, 5))
    plt.plot(xs, ys, label='KDE', linewidth=3)
    # Highlight the local minima
    plt.scatter(minima, ys[minima_idx], color='red', marker='x', label='local minima', s=100)
    # Restrict the x-axis to valid values
    plt.xlim(left=0)
    plt.xlabel('RSA [%]', fontsize=16)
    plt.ylabel('Density', fontsize=16)
    plt.title(f'RSA distribution (all SS)', fontsize=18)
    plt.xticks(fontsize=14)
    plt.yticks(fontsize=14)
    plt.legend()
    plt.tight_layout()
    plt.show()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Plot the KDE and compute the local minima of normalized ACC% across all secondary structure types"
    )
    parser.add_argument('csv_path', help='Path to the input dssp_summary.csv file (must contain an ACC_norm / ACC_norm %% column)')
    parser.add_argument('--points', '-p', type=int, default=1000,
                        help="Number of points used to sample the KDE curve (default: 1000)")
    args = parser.parse_args()
    main(args.csv_path, n_points=args.points)
